def get_setting(name: str, default: str = "") -> str:  # يقرأ الإعداد من متغيرات البيئة (.env) ثم من st.secrets (عند النشر على Streamli
    """يقرأ الإعداد من متغيرات البيئة (.env) ثم من st.secrets (عند النشر على Streamlit Cloud)."""
    value = os.environ.get(name)  # الأولوية لملف .env
    if value:
        return value
    try:
        import streamlit as st  # الاستيراد هنا حتى يعمل الملف خارج Streamlit أيضاً

        return str(st.secrets.get(name, default))  # بديل: أسرار Streamlit
    except Exception:
        return default  # لا .env ولا secrets: نرجع القيمة الافتراضية


def _int_setting(name: str, default: int = 0) -> int:  # يقرأ إعداداً رقمياً بأمان؛ أي قيمة غير رقمية ترجع الافتراضي بدل أن تُسقط المنص
    """يقرأ إعداداً رقمياً بأمان؛ أي قيمة غير رقمية ترجع الافتراضي بدل أن تُسقط المنصة."""
    try:
        return int(get_setting(name, str(default)) or default)
    except ValueError:
        return default


